PASSWORD = "correct-horse-battery-staple"


# --------------------------------------------------------------------------
# The cross-implementation check
# --------------------------------------------------------------------------


def test_a_hash_generated_by_go_verifies_here() -> None:
    """Phase 5's exit check. The hash in the fixture was produced by the Go
    console's own auth package."""
    assert verify_password(MANIFEST["admin_password"], MANIFEST["admin_hash"]) is True


def test_the_go_hash_rejects_a_wrong_password() -> None:
    """Guards against a verify that returns True unconditionally, which would
    make the test above pass for the wrong reason."""
    assert verify_password("not-the-password", MANIFEST["admin_hash"]) is False


def test_the_go_hash_carries_the_documented_parameters() -> None:
    """The schema comment pins these. argon2-cffi's own defaults differ --
    parallelism is 4 there -- so they are set explicitly rather than
    inherited, and this is what would catch that drifting."""
    assert MANIFEST["admin_hash"].startswith("$argon2id$v=19$m=65536,t=3,p=2$")


def test_our_parameters_match_the_go_build() -> None:
    assert (ARGON2_TIME_COST, ARGON2_MEMORY_KIB, ARGON2_PARALLELISM) == (3, 64 * 1024, 2)
    assert (ARGON2_HASH_LEN, ARGON2_SALT_LEN) == (32, 16)


def test_a_hash_we_generate_has_the_same_shape_go_would() -> None:
    """The other direction: Go must be able to verify what we write. The Go
    side of that was confirmed against the real auth package; here we pin the
    encoding so a change would be caught without needing Go present."""
    phc = hash_password(PASSWORD)
    prefix, go_prefix = phc.split("$")[:4], MANIFEST["admin_hash"].split("$")[:4]
    assert prefix == go_prefix


