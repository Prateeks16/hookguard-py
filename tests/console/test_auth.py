def test_policy_accepts_a_reasonable_passphrase() -> None:
    validate_password(PASSWORD)


@pytest.mark.parametrize("length", [0, 1, MIN_PASSWORD_LEN - 1])
def test_policy_rejects_short_passwords(length: int) -> None:
    with pytest.raises(PasswordPolicyError, match="at least"):
        validate_password("a" * length)


def test_policy_rejects_overlong_passwords() -> None:
    """An upper bound is not arbitrary: Argon2 cost scales with input, so an
    unbounded password field is a cheap way to make the server do work."""
    with pytest.raises(PasswordPolicyError, match="at most"):
        validate_password("a" * (MAX_PASSWORD_LEN + 1))


def test_policy_boundaries_are_inclusive() -> None:
    validate_password("a" * MIN_PASSWORD_LEN)
    validate_password("a" * MAX_PASSWORD_LEN)


def test_policy_has_no_composition_rules() -> None:
    """Length only, NIST-style. Composition rules push people toward
    predictable substitutions without adding real entropy."""
    validate_password("aaaaaaaaaaaaaaaa")
    validate_password("             ")


