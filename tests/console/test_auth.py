NOW = datetime(2026, 1, 1, tzinfo=UTC)


def test_allows_up_to_the_limit_then_refuses() -> None:
    limiter = Limiter(3, timedelta(minutes=15))
    for _ in range(3):
        allowed, _ = limiter.allow("a@example.com", NOW)
        assert allowed is True
    allowed, retry_after = limiter.allow("a@example.com", NOW)
    assert allowed is False
    assert retry_after == timedelta(minutes=15)


def test_keys_are_independent() -> None:
    limiter = Limiter(1, timedelta(minutes=15))
    assert limiter.allow("a@example.com", NOW)[0] is True
    assert limiter.allow("b@example.com", NOW)[0] is True
    assert limiter.allow("a@example.com", NOW)[0] is False


def test_the_window_slides_off() -> None:
    limiter = Limiter(2, timedelta(minutes=15))
    limiter.allow("a", NOW)
    limiter.allow("a", NOW)
    assert limiter.allow("a", NOW)[0] is False
    assert limiter.allow("a", NOW + timedelta(minutes=16))[0] is True


def test_retry_after_counts_from_the_oldest_hit() -> None:
    limiter = Limiter(2, timedelta(minutes=15))
    limiter.allow("a", NOW)
    limiter.allow("a", NOW + timedelta(minutes=5))
    _, retry_after = limiter.allow("a", NOW + timedelta(minutes=10))
    assert retry_after == timedelta(minutes=5)


def test_a_refused_attempt_does_not_extend_the_window() -> None:
    """Otherwise an attacker hammering the endpoint keeps the real user locked
    out indefinitely -- the lockout becomes the attack."""
    limiter = Limiter(1, timedelta(minutes=10))
    limiter.allow("a", NOW)
    for minute in range(1, 10):
        limiter.allow("a", NOW + timedelta(minutes=minute))
    assert limiter.allow("a", NOW + timedelta(minutes=11))[0] is True


def test_prune_drops_expired_keys() -> None:
    """The key is attacker-supplied, so an unbounded map is a slow memory leak
    someone can drive."""
    limiter = Limiter(5, timedelta(minutes=15))
    for i in range(100):
        limiter.allow(f"user{i}@example.com", NOW)
    assert limiter.tracked_keys == 100

    assert limiter.prune(NOW + timedelta(minutes=16)) == 100
    assert limiter.tracked_keys == 0


def test_prune_keeps_live_keys() -> None:
    limiter = Limiter(5, timedelta(minutes=15))
    limiter.allow("old", NOW)
    limiter.allow("recent", NOW + timedelta(minutes=14))
    limiter.prune(NOW + timedelta(minutes=16))
    assert limiter.tracked_keys == 1
    # The surviving key keeps its history, so pruning is not a free reset.
    assert limiter.allow("recent", NOW + timedelta(minutes=16))[0] is True


def test_limiter_is_thread_safe() -> None:
    """No race detector in Python, so the concurrent path gets an explicit
    test: N threads against one key must yield exactly `max` allowances."""
    import threading

    limiter = Limiter(50, timedelta(minutes=15))
    results: list[bool] = []
    lock = threading.Lock()

    def hammer() -> None:
        allowed, _ = limiter.allow("shared", NOW)
        with lock:
            results.append(allowed)

    threads = [threading.Thread(target=hammer) for _ in range(200)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()

    assert sum(results) == 50, "the limit must hold exactly under concurrency"
    assert len(results) == 200
