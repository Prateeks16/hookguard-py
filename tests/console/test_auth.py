def test_hash_and_verify_round_trip() -> None:
    phc = hash_password(PASSWORD)
    assert verify_password(PASSWORD, phc) is True
    assert verify_password(PASSWORD + "x", phc) is False


def test_the_salt_is_random_per_hash() -> None:
    """Two users with the same password must not share a hash, or the users
    table leaks who reused a password."""
    assert hash_password(PASSWORD) != hash_password(PASSWORD)


@pytest.mark.parametrize(
    "malformed",
    ["", "not-a-hash", "$argon2id$", "$argon2id$v=19$m=65536,t=3,p=2$onlysalt", "$bcrypt$x$y"],
)
def test_a_malformed_hash_fails_the_login_rather_than_the_request(malformed: str) -> None:
    """A corrupt row in the users table should refuse that login, not raise
    into the handler and 500 the page."""
    assert verify_password(PASSWORD, malformed) is False


def test_verification_uses_the_parameters_in_the_hash_not_ours() -> None:
    """A hash written under different settings -- an older build, or a future
    parameter bump -- must still verify with the right password. That is the
    whole reason the parameters live in the PHC string.

    Asserting only that a foreign hash fails would prove nothing: it fails for
    a dozen reasons. So this generates a genuine hash under deliberately
    different parameters and requires it to VERIFY.
    """
    from argon2 import PasswordHasher, Type

    other = PasswordHasher(
        time_cost=1, memory_cost=8 * 1024, parallelism=1, hash_len=16, salt_len=8, type=Type.ID
    )
    foreign = other.hash(PASSWORD)
    assert foreign.startswith("$argon2id$v=19$m=8192,t=1,p=1$")
    assert foreign.split("$")[3] != hash_password(PASSWORD).split("$")[3], "params must differ"

    assert verify_password(PASSWORD, foreign) is True
    assert verify_password("wrong", foreign) is False


def test_dummy_hash_is_a_real_verifiable_hash() -> None:
    """It exists to make an unknown-email login cost the same as a wrong
    password. A cheap placeholder would defeat that: the timing difference is
    the enumeration oracle."""
    dummy = dummy_hash()
    assert dummy.startswith("$argon2id$")
    assert verify_password("anything", dummy) is False


def test_dummy_hash_is_computed_once() -> None:
    assert dummy_hash() is dummy_hash()


def test_unknown_user_login_costs_about_the_same_as_a_wrong_password() -> None:
    """The point of the dummy hash, measured rather than assumed.

    A generous bound: this asserts the two are within the same order of
    magnitude, not that they are equal. Wall-clock timing on a shared CI
    runner is noisy, and a tight bound here would be a flaky test rather than
    a stronger guarantee.
    """
    real = MANIFEST["admin_hash"]
    dummy = dummy_hash()

    def elapsed(phc: str) -> float:
        start = time.perf_counter()
        verify_password("some-wrong-password", phc)
        return time.perf_counter() - start

    # Warm up, so neither timing pays a one-off import or allocation cost.
    elapsed(real), elapsed(dummy)

    real_t = min(elapsed(real) for _ in range(3))
    dummy_t = min(elapsed(dummy) for _ in range(3))
    ratio = max(real_t, dummy_t) / max(min(real_t, dummy_t), 1e-9)
    assert ratio < 5, f"timings diverge too much: real={real_t:.4f}s dummy={dummy_t:.4f}s"


